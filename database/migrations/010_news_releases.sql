BEGIN;

CREATE TABLE IF NOT EXISTS news_releases (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    title VARCHAR(200) NOT NULL,
    body TEXT NOT NULL,
    is_published BOOLEAN NOT NULL DEFAULT FALSE,
    published_at TIMESTAMPTZ,
    created_by BIGINT REFERENCES users(id) ON DELETE SET NULL,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT news_releases_publication_state CHECK (
        (is_published = TRUE AND published_at IS NOT NULL)
        OR (is_published = FALSE AND published_at IS NULL)
    )
);

CREATE INDEX IF NOT EXISTS idx_news_releases_published
    ON news_releases (published_at DESC, id DESC)
    WHERE is_published = TRUE;

COMMIT;
